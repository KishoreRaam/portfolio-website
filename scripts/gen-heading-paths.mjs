// Build-time generator: converts the work-section heading into real SVG glyph
// outline paths so the stroke can actually be "written" (strokeDashoffset on
// genuine path geometry). Run: node scripts/gen-heading-paths.mjs
import opentype from "opentype.js";
import { writeFileSync, readFileSync } from "node:fs";

const LINES = ["Projects that", "speak for", "themselves"];
const FONT_FILE = "Satisfy.ttf";  // connected signature script (static → clean paths)
const FONT_SIZE = 100;
const LINE_HEIGHT = 104;
const PAD = 10;

const buf = readFileSync(FONT_FILE);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

// One path per GLYPH, in reading order (line by line, left to right). Drawing
// each glyph as its own path lets the pen trace them strictly one after another
// — no dash-phase bleed across the gaps between letters.
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
const glyphs = [];
LINES.forEach((text, i) => {
  const baseline = FONT_SIZE + i * LINE_HEIGHT;
  const paths = font.getPaths(text, 0, baseline, FONT_SIZE);
  paths.forEach((path) => {
    const d = path.toPathData(2);
    if (!d || !d.trim()) return; // spaces produce no outline — skip
    const bb = path.getBoundingBox();
    minX = Math.min(minX, bb.x1); minY = Math.min(minY, bb.y1);
    maxX = Math.max(maxX, bb.x2); maxY = Math.max(maxY, bb.y2);
    glyphs.push(d);
  });
});

const vbX = minX - PAD;
const vbY = minY - PAD;
const vbW = maxX - minX + PAD * 2;
const vbH = maxY - minY + PAD * 2;

const out = `// AUTO-GENERATED by scripts/gen-heading-paths.mjs — do not edit by hand.
export const HEADING_VIEWBOX = "${vbX.toFixed(1)} ${vbY.toFixed(1)} ${vbW.toFixed(1)} ${vbH.toFixed(1)}";
// One entry per glyph, in reading order.
export const HEADING_GLYPHS: string[] = [
${glyphs.map((d) => `  ${JSON.stringify(d)},`).join("\n")}
];
`;

writeFileSync("src/app/components/ui/headingPaths.ts", out);
console.log("Wrote src/app/components/ui/headingPaths.ts");
console.log("glyphs:", glyphs.length, "viewBox:", `${vbX.toFixed(1)} ${vbY.toFixed(1)} ${vbW.toFixed(1)} ${vbH.toFixed(1)}`);
